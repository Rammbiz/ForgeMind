SKELETON = """class_name {cls}
extends RefCounted
## Heroes & Champions data (heroes_design.md §12.2, WS-A). The block below is generated by
## tools/gen_heroes_data.py from tools/data/heroes_consts.json + heroes_roster.json; hand-written
## helpers go after it. Nothing in the shipped game reads this class before EconData.HEROES_PHASE >= 1.

{block}
"""


def render_all() -> dict:
    craw, rraw = open(CONSTS_JSON, "rb").read(), open(ROSTER_JSON, "rb").read()
    consts, roster = json.loads(craw), json.loads(rraw)
    stamp = "Sources: heroes_consts.json sha256 %s, heroes_roster.json sha256 %s." % (
        hashlib.sha256(craw).hexdigest()[:16], hashlib.sha256(rraw).hexdigest()[:16])
    out = {}
    for fname, cls, fn in FILES:
        b = Block(consts, roster)
        fn(b)
        path = os.path.join(ROOT, "scripts", "core", fname + ".gd")
        block = b.text(stamp)
        cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if BEGIN in cur and END in cur:
            i, j = cur.index(BEGIN), cur.index(END) + len(END)
            new = cur[:i] + block + cur[j:]
        else:
            new = SKELETON.format(cls=cls, block=block)
        out[path] = (cur, new)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--refresh", metavar="DIR", nargs="?", const=os.path.join(ROOT, "tools"))
    a = ap.parse_args()
    if a.refresh:
        refresh(a.refresh)
    for p in (CONSTS_JSON, ROSTER_JSON):
        if not os.path.exists(p):
            sys.exit("%s missing (run --refresh <dir>)" % os.path.relpath(p, ROOT))
    files = render_all()
    stale = [p for p, (cur, new) in files.items() if cur != new]
    if a.check:
        for p in stale:
            print("OUT OF DATE: %s (run python3 tools/gen_heroes_data.py)" % os.path.relpath(p, ROOT))
        if stale:
            sys.exit(1)
        print("heroes data in sync: %d files" % len(files))
        return
    for p, (cur, new) in files.items():
        if cur != new:
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(new)
            print("wrote %s" % os.path.relpath(p, ROOT))
    if not stale:
        print("heroes data already in sync")


if __name__ == "__main__":
    main()
