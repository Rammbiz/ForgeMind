# ------------------------------------------------------------------------------------------------ GDScript literals
def _gd(v, as_float: bool = False) -> str:
    """Python value -> GDScript literal (dicts keep insertion order)."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int) and not as_float:
        return str(v)
    if isinstance(v, (int, float)):
        r = repr(float(v))
        return r if ("." in r or "e" in r or "inf" in r or "nan" in r) else r + ".0"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        fl = any(isinstance(x, float) for x in v) and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v)
        return "[" + ", ".join(_gd(x, fl) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join("%s: %s" % (_gd(k), _gd(x)) for k, x in v.items()) + "}"
    raise TypeError(repr(v))


def _scalar_kind(xs) -> str:
    xs = list(xs)
    if not xs:
        return ""
    if all(isinstance(x, bool) for x in xs):
        return "bool"
    if all(isinstance(x, int) and not isinstance(x, bool) for x in xs):
        return "int"
    if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in xs):
        return "float"
    if all(isinstance(x, str) for x in xs):
        return "String"
    return ""


def _const(name: str, v) -> str:
    """Typed const line: scalars, homogeneous Array[T], homogeneous flat Dictionary[String, T]."""
    if isinstance(v, bool):
        return "const %s := %s" % (name, _gd(v))
    if isinstance(v, int):
        return "const %s: int = %s" % (name, _gd(v))
    if isinstance(v, float):
        return "const %s: float = %s" % (name, _gd(v))
    if isinstance(v, str):
        return "const %s: String = %s" % (name, _gd(v))
    if isinstance(v, (list, tuple)):
        k = _scalar_kind(v)
        if k:
            return "const %s: Array[%s] = [%s]" % (name, k, ", ".join(_gd(x, k == "float") for x in v))
        return "const %s: Array = %s" % (name, _gd(v))
    if isinstance(v, dict):
        k = _scalar_kind(v.values())
        if k and all(isinstance(x, str) for x in v):
            return "const %s: Dictionary[String, %s] = {%s}" % (
                name, k, ", ".join("%s: %s" % (_gd(a), _gd(b, k == "float")) for a, b in v.items()))
        return "const %s: Dictionary = %s" % (name, _gd(v))
    raise TypeError(name)


class Block:
    """Collects the const lines and the SOURCE_KEYS table of one generated block."""

    def __init__(self, consts: dict, roster: dict):
        self.c, self.r = consts, roster
        self.lines: list[str] = []
        self.src: dict[str, str] = {}

    @staticmethod
    def _at(root, path: str):
        v = root
        for p in path.split("."):
            v = v[p]
        return v

    def head(self, text: str) -> None:
        self.lines += ["", "# ---- " + text]

    def doc(self, text: str) -> None:
        self.lines += ["## " + t for t in text.split("\n")]

    def emit(self, name: str, value, source: str, comment: str = "") -> None:
        if comment:
            self.doc(comment)
        self.lines.append(_const(name, value))
        self.src[name] = source

    def consts(self, name: str, path: str, comment: str = "") -> None:
        self.emit(name, self._at(self.c, path), "consts:" + path, comment)

    def roster(self, name: str, path: str, comment: str = "") -> None:
        self.emit(name, self._at(self.r, path), "roster:" + path, comment)

    def docv(self, name: str, comment: str = "") -> None:
        v, ref = DOC[name]
        self.emit(name, v, "doc:" + ref, comment + (" " if comment else "") + "(heroes_design.md %s)" % ref)

    def rows(self, name: str, path: str, order: list, comment_of) -> None:
        """A roster dictionary written one row per line with a trailing comment."""
        rows = self._at(self.r, path)
        self.lines.append("const %s: Dictionary = {" % name)
        for k in order:
            self.lines.append("\t%s: %s,  # %s" % (_gd(k), _gd(rows[k]), comment_of(k, rows[k])))
        self.lines.append("}")
        self.src[name] = "roster:" + path

    def text(self, stamp: str) -> str:
        out = [BEGIN, "## " + stamp] + self.lines
        out += ["", "## Where every generated constant comes from: consts:<path> = tools/data/heroes_consts.json,",
                "## roster:<path> = tools/data/heroes_roster.json (both checked by scripts/dev/test_heroes.gd),",
                "## doc:<§> = heroes_design.md, derived:<rule> = computed by the generator from the json."]
        out.append("const SOURCE_KEYS: Dictionary[String, String] = {")
        out += ["\t%s: %s," % (_gd(k), _gd(v)) for k, v in self.src.items()]
        out += ["}", END]
        return "\n".join(out)


