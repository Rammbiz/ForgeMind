def _parse_roster_tables(md: str) -> tuple[dict, dict]:
    """heroes_design.md §6.0: hero rows (№, ult kind, second element of form V) and champion rows (№)."""
    sec = md[md.index("### 6.0 At a glance"):md.index("### 6.1 ")]
    heroes, champs = {}, {}
    for line in sec.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 10 or not re.fullmatch(r"\d\d", cells[0]):
            continue
        cid = cells[1].strip("`")
        no = int(cells[0])
        if len(cells) == 12:   # hero table: № id Name Title Gem Class Element Faction Species Niche Ult Source
            m = re.search(r"\(\+(\w+) in V\)", cells[6])
            heroes[cid] = {"no": no, "ult": cells[10].strip("`"), "element2": m.group(1).lower() if m else "",
                           "niche": "" if cells[9] in ("—", "-") else cells[9].strip("`")}
        else:
            champs[cid] = {"no": no}
    if len(heroes) != 10 or len(champs) != 12:
        sys.exit("heroes_design.md §6.0 tables changed shape (%d heroes, %d champions)" % (len(heroes), len(champs)))
    return heroes, champs


def _gem_dict(d: dict) -> dict:
    """{gem: p} in gem order with every gem of the table present (0.0 when absent)."""
    keys = [g for g in GEMS if g in d] if len(d) < 5 else GEMS
    return {g: float(d.get(g, 0.0)) for g in keys}


def _low(s: str) -> str:
    s = s.lower()
    return "celestial" if s == "celestials" else s


