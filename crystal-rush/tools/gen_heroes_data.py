def block_ladder(b: Block) -> None:
    b.head("gems (keys = the Meta-1 rarity enum; display names come from Loc GEM_C ... GEM_M)")
    b.roster("GEMS", "gems.keys")
    b.roster("GEM_NAME_UK", "gems.uk", "Reference names (Кварц, Сапфір, Аметист, Топаз, Опал); UI copy reads Loc, never these.")
    b.roster("GEM_NAME_EN", "gems.en")
    b.roster("HERO_MAX_GEM", "hero_max_gem")
    b.roster("CHAMPION_MAX_GEM", "champion_max_gem", "Champion recut stops at Topaz (§4.1).")
    b.head("B1 stats: ladder(n, g, f) = NATIVE_MULT[n] x RECUT_STEP^(g - n) x (1 + FACET_STEP f)  (§2.2)")
    for k in ("Q_NATIVE", "FACET_STEP", "NATIVE_MULT", "RECUT_STEP", "CEILING", "FACETS_PER_GEM"):
        b.consts(k, "ladder." + k)
    b.head("B2 skills (F-CAP): skill_cap(n, g, f) = SKILL_BASE[g] - [g > n] + [f == FACETS_PER_GEM]")
    b.consts("SKILL_BASE", "ladder.SKILL_BASE")
    b.head("B3 ult forms: ult_form(n, rank) = min(n + 1, #{FORM_AT_RANK <= rank})")
    b.consts("FORM_AT_RANK", "ladder.FORM_AT_RANK")
    b.head("B4 Awakening (F-AWK2): can_awaken = g >= AWAKEN_MIN_GEM and (f == 5 or (g == n and n >= BORN_AWAKENED_MIN))")
    b.consts("AWAKEN_MIN_GEM", "ladder.AWAKEN_MIN_GEM")
    b.consts("AWAKEN_CAP", "ladder.AWAKEN_CAP", "awaken_cap(n, g) = AWAKEN_CAP[g] - [g > n] (0 below AWAKEN_MIN_GEM).")
